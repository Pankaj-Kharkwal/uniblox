ROOT = Path(__file__).resolve().parent.parent


def test_todo_scaffold_is_plain_pydantic_with_enums_and_exact() -> None:
    proj = scaffold(load(ROOT / "examples" / "todo.loom"))
    assert proj.package == "todo_list" and not proj.has_db and not proj.has_api
    models = proj.files["src/todo_list/models.py"]
    assert models.startswith("# Generated by Loom from todo.loom (things).")
    assert "class TaskStatus(StrEnum):\n    OPEN = 'open'\n    DONE = 'done'" in models
    assert "priority: TaskPriority = TaskPriority.NORMAL" in models
    assert "due: Optional[date] = None" in models
    assert "model_config = ConfigDict(validate_assignment=True)" in models
    assert strip_header(proj.files["src/todo_list/exact.py"]) == (
        'def normalize_title(title: str) -> str:\n    return " ".join(title.split()).casefold()\n'
    )
    assert "src/todo_list/db.py" not in proj.files
    assert (
        "'complete_task:R1': 'never complete a task that is already done'"
        in (proj.files["src/todo_list/runtime.py"])
    )
    assert '"sqlmodel' not in proj.files["pyproject.toml"]


def test_invoice_scaffold_uses_sqlmodel_tables_and_tz_safe_datetimes() -> None:
    proj = scaffold(load(ROOT / "examples" / "invoice_chaser.loom"))
    assert proj.has_db and proj.has_api
    models = proj.files["src/invoice_chaser/models.py"]
    assert "class Invoice(SQLModel, table=True):" in models
    assert "client_email: EmailStr = Field(sa_type=AutoString)" in models
    assert (
        'amount: Decimal = Field(max_digits=14, decimal_places=2, description="money (INR)")'
        in (models)
    )
    assert (
        "last_reminded_at: Optional[datetime] = Field(default=None, sa_type=UTCDateTime)" in models
    )
    assert "CURRENCIES: dict[str, str] = {'Invoice.amount': 'INR'}" in models
    pyproject = proj.files["pyproject.toml"]
    for dep in ("sqlmodel", "fastapi", "apscheduler", "pytest", "hypothesis"):
        assert dep in pyproject


def test_generated_scaffold_runs(tmp_path: Path) -> None:
    fe = load(ROOT / "examples" / "invoice_chaser.loom")
    proj = scaffold(fe)
    stub = "def chase_overdue_invoices(session, *, now=None):\n    return []\n"
    files = {**proj.files, "src/invoice_chaser/chase_overdue_invoices.py": stub}
    files.update(
        glue_files(
            fe,
            proj,
            [
                BlockGlue(
                    "chase_overdue_invoices",
                    True,
                    True,
                    True,
                    Schedule("0 10 * * mon-fri", "Asia/Kolkata"),
                )
            ],
        )
    )
    write_files(tmp_path, files)
    script = """
from datetime import UTC, date, datetime, timedelta
from decimal import Decimal
from sqlmodel import select
from invoice_chaser.db import memory_session
from invoice_chaser.models import Invoice, InvoiceStatus
from invoice_chaser.outbox import queue_email, queued_emails
from invoice_chaser.runtime import RuleViolation, guard
from invoice_chaser import api, scheduler
now = datetime(2026, 3, 11, 4, 30, tzinfo=UTC)
with memory_session() as s:
    s.add(Invoice(client="A", client_email="a@x.in", amount=Decimal("10.50"), due=date(2026, 3, 1),
                  status=InvoiceStatus.SENT, last_reminded_at=now - timedelta(hours=2)))
    s.commit(); s.expire_all()
    inv = s.exec(select(Invoice)).one()
    assert inv.last_reminded_at == now - timedelta(hours=2) and inv.status == "sent"
    queue_email(s, to=inv.client_email, subject="s", body="b", now=now)
    assert [e.to for e in queued_emails(s)] == ["a@x.in"]
try:
    guard(False, "chase_overdue_invoices:R1")
except RuleViolation as e:
    assert "never email the same client twice in 24h" in str(e)
assert [j.id for j in scheduler.build_scheduler().get_jobs()] == ["chase_overdue_invoices"]
assert "/jobs/chase_overdue_invoices" in [r.path for r in api.app.routes]
print("ok")
"""
    res = subprocess.run(
        [sys.executable, "-c", script],
        cwd=tmp_path,
        env={"PYTHONPATH": str(tmp_path / "src")},
        capture_output=True,
        text=True,
    )
    assert res.stdout.strip() == "ok", res.stderr


def test_glue_skips_functions_that_need_arguments() -> None:
    fe = load(ROOT / "examples" / "invoice_chaser.loom")
    proj = scaffold(fe)
    glue = glue_files(fe, proj, [BlockGlue("chase_overdue_invoices", True, True, False)])
    scheduler = glue["src/invoice_chaser/scheduler.py"]
    assert "run_chase_overdue_invoices" not in scheduler
    assert "def build_scheduler()" in scheduler
    assert "/jobs/" not in glue["src/invoice_chaser/api.py"]


def test_reserved_names_are_rejected() -> None:
    with pytest.raises(LoomSyntaxError, match="field name 'class' is reserved"):
        scaffold(load_text("app X\ntarget: python 3.12\nthing T\n  class: text\n"))
    with pytest.raises(LoomSyntaxError, match="clashes with a generated module"):
        scaffold(load_text("app X\ntarget: python 3.12\ndoes models\n  x\n"))
