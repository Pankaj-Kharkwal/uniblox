# --- glue written after codegen ------------------------------------------------------------


def glue_files(fe: Frontend, proj: Project, glue: list[BlockGlue]) -> dict[str, str]:
    """``scheduler.py`` and ``api.py``, which call the generated functions."""
    out: dict[str, str] = {}
    pkg = proj.package
    scheduled = [g for g in glue if g.schedule and g.callable_without_args]
    if any(d.trigger for d in fe.program.does):
        out[f"src/{pkg}/scheduler.py"] = proj.header("scheduler") + _scheduler(proj, scheduled)
    if proj.has_api:
        out[f"src/{pkg}/api.py"] = proj.header("api") + _api(proj, glue)
    return out


def _call(g: BlockGlue, session: str = "session") -> str:
    args = []
    if g.takes_session:
        args.append(session)
    if g.takes_now:
        args.append("now=utcnow()")
    return f"{g.slug}({', '.join(args)})"


def _scheduler(proj: Project, jobs: list[BlockGlue]) -> str:
    pkg = proj.package
    imports = sorted({f"from {pkg}.{g.slug} import {g.slug}" for g in jobs})
    runners = []
    table = []
    for g in jobs:
        assert g.schedule is not None
        if g.takes_session:
            body = f"    with session_scope() as session:\n        {_call(g)}"
        else:
            body = f"    {_call(g)}"
        runners.append(f"def run_{g.slug}() -> None:\n{body}\n")
        table.append(
            f"    ({g.slug!r}, run_{g.slug}, {g.schedule.cron!r}, {g.schedule.timezone!r}),"
        )
    db_import = f"from {pkg}.db import session_scope\n" if proj.has_db else ""
    jobs_src = "\n".join(table)
    runners_src = "\n\n".join(runners)
    return f'''"""Runs the scheduled does blocks (APScheduler): `python -m {pkg}.scheduler`."""

from __future__ import annotations

from collections.abc import Callable

from apscheduler.schedulers.blocking import BlockingScheduler
from apscheduler.triggers.cron import CronTrigger

{db_import}from {pkg}.runtime import utcnow
{chr(10).join(imports)}


{runners_src}

# (job id, function, crontab, timezone)
JOBS: list[tuple[str, Callable[[], None], str, str]] = [
{jobs_src}
]


def build_scheduler() -> BlockingScheduler:
    scheduler = BlockingScheduler()
    for job_id, func, crontab, tz in JOBS:
        scheduler.add_job(func, CronTrigger.from_crontab(crontab, timezone=tz), id=job_id)
    return scheduler


if __name__ == "__main__":
    build_scheduler().start()
'''


def _api(proj: Project, glue: list[BlockGlue]) -> str:
    pkg = proj.package
    jobs = [g for g in glue if g.callable_without_args]
    imports = sorted({f"from {pkg}.{g.slug} import {g.slug}" for g in jobs})
    routes = []
    for g in jobs:
        if g.takes_session:
            body = f"    with session_scope() as session:\n        {_call(g)}\n"
        else:
            body = f"    {_call(g)}\n"
        routes.append(
            f'@app.post("/jobs/{g.slug}")\ndef job_{g.slug}() -> dict[str, str]:\n'
            f'    """Run `{g.slug}` now."""\n{body}    return {{"status": "done"}}\n'
        )
    db_import = f"from {pkg}.db import session_scope\n" if proj.has_db else ""
    return f'''"""HTTP entry points. Run with `uvicorn {pkg}.api:app`."""

from __future__ import annotations

from fastapi import FastAPI

{db_import}from {pkg}.runtime import utcnow
{chr(10).join(imports)}

app = FastAPI(title={proj.app_name!r})


@app.get("/health")
def health() -> dict[str, str]:
    return {{"status": "ok"}}


{chr(10).join(routes)}'''


